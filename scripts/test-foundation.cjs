const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const engine=require('./learning-engine.cjs');
const course=JSON.parse(fs.readFileSync(path.join(__dirname,'../content/foundation/course.json'),'utf8'));
const lesson=course.lessons[0];
const multi=lesson.objectives[1].questions[0];
assert.equal(engine.grade(multi,multi.correctChoiceIds).correct,true);
assert.equal(engine.grade(multi,multi.choices.map(c=>c.id)).correct,false);
assert.equal(engine.grade(multi,[multi.correctChoiceIds[0]]).correct,false);
assert.throws(()=>engine.grade(multi,['invalid']));
assert.throws(()=>engine.grade(multi,[]));
assert.throws(()=>engine.grade(multi,[multi.correctChoiceIds[0],multi.correctChoiceIds[0]]));
const first=engine.pick(lesson,{},[],()=>0);
const second=engine.pick(lesson,{},first.map(q=>q.questionId),()=>0);
assert(first.every((q,i)=>q.questionId!==second[i].questionId));
const third=engine.pick(lesson,{},[...first,...second].map(q=>q.questionId),()=>0);
assert(third.every((q,i)=>q.questionId!==first[i].questionId&&q.questionId!==second[i].questionId));
assert.equal(engine.pick(lesson,{[lesson.objectives[0].id]:true},[]).length,2);
assert.deepEqual(engine.pick(lesson,Object.fromEntries(lesson.objectives.map(o=>[o.id,true])),[]),[]);

// Exercise actual preview event handlers with a minimal DOM, including persistence.
const storage=new Map(),nodes={},events={};
const node=id=>nodes[id]||=( {innerHTML:'',textContent:'',checked:false,focus(){},scrollIntoView(){},setAttribute(){}} );
node('course-data').textContent=JSON.stringify(course);
const document={getElementById:node,addEventListener:(type,fn)=>events[type]=fn};
const localStorage={getItem:key=>storage.get(key)||null,setItem:(key,value)=>storage.set(key,value)};
const context=vm.createContext({document,window:{scrollTo(){},confirm(){return true}},localStorage,LearningEngine:engine,console,Date,Math,Blob,URL,setTimeout});
const source=fs.readFileSync(path.join(__dirname,'../content/foundation/preview.js'),'utf8');
vm.runInContext(source,context);
const read=code=>vm.runInContext(code,context);
const click=action=>events.click({target:{closest:()=>({dataset:{action}})}});
assert.equal(read('unlocked(1)'),false);
click('start');assert.equal(read('state.quiz.rows.length'),3);
read(`state.quiz.rows.forEach((r,i)=>{const {q}=lookup(current(),r);r.selected=i===1?[q.choices.find(c=>!q.correctChoiceIds.includes(c.id)).id]:[...q.correctChoiceIds];});`);
events.submit({target:{id:'quiz-form'},preventDefault(){}});
assert.equal(read('state.attempts.length'),3);
assert.equal(read('Object.keys(state.confirmed).length'),2);
assert.equal(read('unlocked(1)'),false);
// Submission is idempotent, so repeated events cannot duplicate an attempt.
events.submit({target:{id:'quiz-form'},preventDefault(){}});
assert.equal(read('state.attempts.length'),3);
click('read');assert(nodes.main.innerHTML.includes('data-action="retry"'));
const old=read('state.quiz.rows[1].questionId');
click('retry');assert.equal(read('state.quiz.rows.length'),1);
assert.notEqual(read('state.quiz.rows[0].questionId'),old);
assert.equal(read('state.quiz.rows[0].supported'),true);
read(`state.quiz.rows[0].selected=[...lookup(current(),state.quiz.rows[0]).q.correctChoiceIds];`);
events.submit({target:{id:'quiz-form'},preventDefault(){}});
assert.equal(read('done(current())'),true);assert.equal(read('unlocked(1)'),true);
assert.equal(read('state.confirmed["PC01-O2"].assisted'),true);
assert.equal(read('state.attempts.length'),4);
click('next');assert.equal(read('state.lessonIndex'),1);
click('start');click('read');assert(nodes.main.innerHTML.includes('data-action="resume"'));
const retained=read('state.quiz.id');click('resume');assert.equal(read('state.quiz.id'),retained);
events.change({target:{id:'review-switch',checked:true}});assert.equal(read('unlocked(11)'),true);
events.click({target:{closest:()=>({dataset:{lesson:'11'}})}});assert.equal(read('state.lessonIndex'),11);
events.change({target:{id:'review-switch',checked:false}});assert.equal(read('state.lessonIndex'),1);
assert.equal(read('state.attempts.length'),4);
const restored=JSON.parse(storage.get('ai-campus-foundation-preview-v1'));
assert.equal(restored.attempts.length,4);assert.equal(restored.confirmed['PC01-O2'].assisted,true);
const reloadNodes={};
const reloadNode=id=>reloadNodes[id]||=({innerHTML:'',textContent:id==='course-data'?JSON.stringify(course):'',checked:false,focus(){}});
const reloadContext=vm.createContext({document:{getElementById:reloadNode,addEventListener(){}},window:{scrollTo(){}},localStorage,LearningEngine:engine,console,Date,Math,Blob,URL,setTimeout});
vm.runInContext(source,reloadContext);
assert.equal(vm.runInContext('state.attempts.length',reloadContext),4);
assert.equal(vm.runInContext('state.lessonIndex',reloadContext),1);
// Finish the remaining course through its actual submit/next handlers.
for(let i=1;i<course.lessons.length;i++){
 assert.equal(read('state.lessonIndex'),i);click('start');
 read(`state.quiz.rows.forEach(r=>r.selected=[...lookup(current(),r).q.correctChoiceIds]);`);
 events.submit({target:{id:'quiz-form'},preventDefault(){}});
 assert.equal(read('done(current())'),true);click('next');
}
assert.equal(read('course.lessons.filter(done).length'),12);
assert.equal(read('state.view'),'records');
assert(nodes.main.innerHTML.includes('課題の提出・講師の確認はまだ行えません'));
console.log('PASS: grading, multi-select over/under-selection, invalid answers, balanced redraw, retry only failed objective, supported pass, unlock, duplicate submission, resume, review-mode isolation and stored history.');
console.log('PASS: restored session and complete 12-lesson progression to the instructor-reviewed final assignment notice.');
